type RefugeSeed = {
  slug: string;
  name: string;
  nearestTown: string;
  county: string;
  region: TexasRegion;
  lat: number;
  lng: number;
  habitatHero: keyof typeof habitatHeroes;
  officialSlug: string;
  habitat: string;
  wildlife: string;
  experience: string;
  season: string;
  planning: string;
  formerName?: string;
};

function refuge(seed: RefugeSeed): Destination {
  const formerName = seed.formerName ? ` Formerly known as ${seed.formerName}, the refuge now uses its current federal name.` : "";
  return {
    id: `wildlife-refuge-${seed.slug}`,
    brandId: "texasdefined",
    slug: seed.slug,
    name: seed.name,
    summary: `${seed.name} protects ${seed.habitat} near ${seed.nearestTown}, giving Texas travelers a public place to understand habitat conservation, bird migration and native wildlife in the field.${formerName}`,
    category: "outdoors",
    region: seed.region,
    nearestTown: seed.nearestTown,
    county: seed.county,
    coordinates: { lat: seed.lat, lng: seed.lng },
    hero: habitatHeroes[seed.habitatHero],
    bestSeason: seed.season,
    entryNote: seed.planning,
    highlights: [seed.habitat, seed.wildlife, seed.experience],
    body: [
      `${seed.name} is part of the U.S. National Wildlife Refuge System and is managed first for wildlife and habitat. The landscape here is defined by ${seed.habitat}. That conservation purpose is the reason the refuge feels different from a city park or recreation-first destination: visitor access is designed around protecting habitat while still allowing people to watch wildlife, learn the landscape and experience a part of Texas that is increasingly difficult to see elsewhere.${formerName}`,
      `For visitors, the strongest reason to come is ${seed.experience}. Wildlife varies by season and conditions, but the refuge is particularly associated with ${seed.wildlife}. Bring binoculars, water, sun protection and insect repellent when conditions call for them, and treat posted closures as part of the conservation experience rather than an inconvenience. Refuge roads, trails, water access and wildlife viewing areas can change with weather, habitat work and seasonal management.`,
      `${seed.name} also works as a regional anchor rather than an isolated pin on a map. Its ${seed.county} County location connects naturally with TexasDefined's county guide, nearby public lands and the broader ${seed.region.replaceAll("-", " ")} travel region. Use the official U.S. Fish and Wildlife Service page before departure for current hours, fees, hunting or fishing rules, temporary closures and accessibility details, then use the TexasDefined links on this page to continue building the surrounding trip.`,
    ],
    managingAuthority: "U.S. Fish and Wildlife Service",
    officialUrl: `https://www.fws.gov/refuge/${seed.officialSlug}`,
    sourceCheckedAt: checkedAt,
  };
}

