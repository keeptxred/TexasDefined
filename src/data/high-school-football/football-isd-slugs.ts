export function footballIsdSlug(value: string) {
  return value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[’']/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function footballIsdProfilePath(value: string) {
  return `/texas-high-school-football-isds/${footballIsdSlug(value)}`;
}
