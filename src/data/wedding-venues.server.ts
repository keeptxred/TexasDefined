const slugify = (value: string) =>
  value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const regionBySlug = new Map(WEDDING_VENUE_REGIONS.map((region) => [region.slug, region]));

export const WEDDING_VENUES: WeddingVenue[] = WEDDING_VENUE_REGIONS.flatMap((region) =>
  REGION_VENUE_NAMES[region.slug].map((name, index) => {
    const slug = slugify(name);
    const location = CURATED_LOCATIONS[slug];
    return {
      name,
      slug,
      regionSlug: region.slug,
      regionName: region.name,
      position: index + 1,
      city: location?.city,
      countySlug: location?.countySlug,
      locationStatus: location ? 'county-curated' : 'region-only',
    };
  }),
);

const venueBySlug = new Map(WEDDING_VENUES.map((venue) => [venue.slug, venue]));

export function findWeddingVenue(slug: string) {
  return venueBySlug.get(slugify(slug));
}

export function weddingVenuesForRegion(regionSlug: string) {
  return WEDDING_VENUES.filter((venue) => venue.regionSlug === regionSlug);
}

export function weddingVenuesForCounty(countySlug: string) {
  return WEDDING_VENUES
    .filter((venue) => venue.countySlug === countySlug)
    .sort((left, right) => left.name.localeCompare(right.name));
}

export function findWeddingVenueRegion(regionSlug: string) {
  return regionBySlug.get(regionSlug as WeddingVenueRegionSlug);
}

