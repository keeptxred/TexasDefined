#!/usr/bin/env node
// Keep the lightweight homepage card in parity with the full USS Lexington article.
// This is intentionally a narrow source-backed metadata generator: the 20kB article
// body must not be imported into the homepage/client catalog bundle.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { calculateArticleReadingMinutes } from "../../src/data/article-reading-time.ts";
import { ussLexingtonCv16HistoryVisitorGuideArticle } from "../../src/data/fixtures/uss-lexington-cv16-history-visitor-guide.ts";

const destination = fileURLToPath(new URL("../../src/data/fixtures/uss-lexington-reading-time.generated.ts", import.meta.url));
const minutes = calculateArticleReadingMinutes(ussLexingtonCv16HistoryVisitorGuideArticle);
const generated = [
  "// AUTO-GENERATED by scripts/data/generate-uss-lexington-reading-time.mjs.",
  "// Derived from the published USS Lexington full article body at 220 words/minute.",
  "// Do not edit manually; the homepage parity gate rejects stale values.",
  `export const USS_LEXINGTON_CV16_READING_MINUTES = ${minutes};`,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== generated) {
    console.error(`USS Lexington reading-time metadata is stale. Run node --experimental-strip-types scripts/data/generate-uss-lexington-reading-time.mjs to regenerate (${minutes} minutes expected).`);
    process.exitCode = 1;
  } else {
    console.log(`USS Lexington reading-time metadata verified: ${minutes} minutes.`);
  }
} else {
  writeFileSync(destination, generated);
  console.log(`Wrote USS Lexington reading-time metadata: ${minutes} minutes.`);
}
