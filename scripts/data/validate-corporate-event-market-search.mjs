import assert from 'node:assert/strict';
import { corporateEventProviders } from '../../src/data/corporate-events.ts';
import { corporateEventMarketMatches, normalizeCorporateEventMarketQuery } from '../../src/data/corporate-event-market-search.ts';
import { readFileSync } from 'node:fs';

const by = (query) => corporateEventProviders.filter((provider) => corporateEventMarketMatches(provider, query));
assert.equal(normalizeCorporateEventMarketQuery('Houston, TX'), 'houston');
assert.equal(normalizeCorporateEventMarketQuery('Houston Texas'), 'houston');
assert.equal(normalizeCorporateEventMarketQuery('Dallas/Fort Worth'), 'dallas fort worth');
assert.equal(normalizeCorporateEventMarketQuery('TX'), 'texas');
assert(by('Houston').length >= 10, 'Houston city match');
assert.equal(by('Houston TX').length, by('Houston').length);
assert.equal(by('Houston, Texas').length, by('Houston').length);
assert.equal(by('77002').length, corporateEventProviders.filter((p) => p.city === 'Houston').length, 'Houston ZIP searches should match Houston-city listings, not incorrectly include Katy and other suburbs');
assert.equal(by('77201').length, corporateEventProviders.filter((p) => p.city === 'Houston').length);
assert(by('Austin, TX').length >= 3, 'Austin city match');
assert(by('San Antonio TX').length >= 3, 'San Antonio city match');
assert(by('DFW').length >= 3, 'DFW metro alias must match');
assert.equal(by('DFW').length, by('Dallas/Fort Worth').length, 'DFW and Dallas/Fort Worth must find the same catalog');
assert(by('Fort Worth, TX').length >= 1, 'Fort Worth suburban/metro matches');
assert.equal(by('Texas').length, corporateEventProviders.length, 'Statewide lookup');
assert.equal(by('TX').length, corporateEventProviders.length);
assert.equal(by('').length, 0);
assert.equal(by('Atlanta').length, 0, 'Do not include unrelated markets');
const route=readFileSync('src/routes/corporate-events.lazy.tsx', 'utf8');
assert(route.includes('corporateEventMarketMatches(provider, cityTerm)'));
assert(!route.includes("cityTerm.replace(/,?\\\\s+"), 'No double-escaped whitespace regex in live city filter');
assert(!route.includes('^77(?:0|2)\\\\d'), 'No double-escaped ZIP regex in live city filter');
console.log('Corporate events: Houston TX, 77002, Austin, DFW, Fort Worth, San Antonio, statewide search PASS.');
